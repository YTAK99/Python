'''함수'''

def visit(today, *customers):
    print(today)
    for customer in customers:
        print(customer)

visit('2022년 6월 10일', '나장발') # 1명 방문
visit('2022년 6월 10일', '나장발', '나수염') # 2명 방문
visit('2022년 6월 10일', '나장발', '나수염', '나김리') # 3명 방문

