'''2중 for문 - 구구단'''

N = int(input())
x = 1

while x <= 9:
    print(f'{N} * {x} = {N*x}')
    x += 1

########################################################################################

S = int(input())
E = int(input())

# S가 E보다 작으면 1씩 증가, 크면 -1씩 감소
step = 1 if S <= E else -1

for x in range(S, E + step, step):
    print(x, end=' ')   

########################################################################################

# 입력값을 순서대로 출력
for n in sorted(map(int, input().split())):
    print(n)

