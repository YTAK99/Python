# 오른쪽정렬

for i in range(1,4):
    print(f'{("*"*i):>3}')
    
########################################################

for i in range(1, 4):
    print(('*' * i).rjust(3))

########################################################

for i in range(1, 4):
    print('{:>3}'.format('*' * i))
    
########################################################

for i in range(1, 4):
    print(' ' * (3 - i) + '*' * i)

########################################################

for i in range(1, 4):
    print('%3s' % ('*' * i))
