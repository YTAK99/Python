# 오른쪽정렬

for x in range(1,4):
    print(f'{("*"*x):>3}')
    
########################################################

for x in range(1, 4):
    print(('*' * x).rjust(3))

########################################################

for x in range(1, 4):
    print('{:>3}'.format('*' * x))
    
########################################################

for x in range(1, 4):
    print(' ' * (3 - x) + '*' * x)

########################################################

for x in range(1, 4):
    print('%3s' % ('*' * x))
