# 소인수분해

def solution(n):
    result = []

    for x in range(2, n+1):  # 소인수는 2부터 시작하므로 2부터 n까지 검사
        if (n % x == 0):  # 1. x가 n의 약수인지 확인 (나머지가 0인지 확인)
            is_prime = True  # 2. 그 약수(x)가 '소수'인지 확인
            for i in range(2, x):
                if x % i == 0:
                    is_prime = False
                    break
            if is_prime and (x not in result):  # 3. 소수가 맞고, 아직 결과 배열에 없다면 추가
                result.append(x)
    return sorted(result)

