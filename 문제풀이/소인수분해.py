def solution(n):
    answer = []
    d = 2
    
    # d를 2부터 시작하여 n을 나눌 수 없을 때까지 나눕니다.
    while d * d <= n:
        if n % d == 0:
            answer.append(d)
            # n에서 해당 소인수를 완전히 제거할 때까지 나눕니다 (중복 제거)
            while n % d == 0:
                n //= d
        d += 1
    
    # 나누고 남은 n이 1보다 크다면, 그 수 자체가 마지막 소인수입니다.
    if n > 1:
        answer.append(n)
        
    return answer

